def test_cli_stdout_end_to_end(tmp_path: Path, capsys) -> None:
    ws = make_workspace(tmp_path)
    output = tmp_path / "RECORD.md"
    cfg = make_config(ws, output)

    assert main(["--config", str(cfg), "--stdout"]) == 0
    captured = capsys.readouterr()
    text, summary = captured.out, captured.err

    assert "# The Annals" in text
    assert "Custom intro. Generated by annals " in text  # {generator} replaced
    assert (
        "| [repo-a](https://example.com/repo-a) | The first repo | 2 | 1.1.0"
        " | 2026-03-05 | 1 | 2026-01-01 |" in text
    )
    assert "authored by Test Author" in text
    assert "larocque.brandon@gmail.com" not in text
    assert "test@example.com" not in text
    assert "- **03-05 · repo-a 1.1.0** · Two" in text
    assert "- **01-01 · repo-a 1.0.0** · One" in text
    assert "calibre" not in text
    assert "| sb | 0 |" in text
    assert "stray" in summary
    assert not output.exists()
    assert not (tmp_path / "site" / "patchnotes.md").exists()
    assert not (tmp_path / "site" / "_includes" / "ledger.md").exists()
    assert not (tmp_path / "site" / "patchnotes" / "feed.xml").exists()


def test_cli_write_then_check(tmp_path: Path, capsys) -> None:
    ws = make_workspace(tmp_path)
    output = tmp_path / "RECORD.md"
    cfg = make_config(ws, output)

    assert main(["--config", str(cfg)]) == 0
    assert output.exists()
    site_out = tmp_path / "site" / "patchnotes.md"
    site_text = site_out.read_text(encoding="utf-8")
    assert site_text.startswith("---\nlayout: default\npermalink: /patchnotes/\n---\n")
    assert "{% raw %}" in site_text and "{% endraw %}" in site_text
    assert "# The Annals" in site_text
    ledger_out = tmp_path / "site" / "_includes" / "ledger.md"
    ledger_text = ledger_out.read_text(encoding="utf-8")
    assert ledger_text.startswith("As of ")
    assert ledger_text.endswith("own log.\n")
    assert "[the patchnotes]({{ '/p/' | relative_url }})" in ledger_text
    assert "{% raw %}" not in ledger_text
    feed_out = tmp_path / "site" / "patchnotes" / "feed.xml"
    feed_text = feed_out.read_text(encoding="utf-8")
    assert feed_text.startswith('<?xml version="1.0" encoding="utf-8"?>')
    assert feed_text.count("<entry>") == 1  # the [feed] limit
    assert "<id>tag:example.com,2026:2026-03-05/repo-a/1.1.0</id>" in feed_text
    assert "<subtitle>Every release, newest first.</subtitle>" in feed_text
    assert "<id>tag:example.com,2026:/p/</id>" in feed_text
    assert '<link rel="self" href="https://example.com/p/feed.xml"/>' in feed_text
    assert '<link rel="alternate" href="https://example.com/p/"/>' in feed_text
    capsys.readouterr()

    assert main(["--config", str(cfg), "--check"]) == 0
    capsys.readouterr()

    before_ledger = ledger_out.read_text(encoding="utf-8")
    before_feed = feed_out.read_text(encoding="utf-8")
    assert main(["--config", str(cfg)]) == 0
    assert ledger_out.read_text(encoding="utf-8") == before_ledger
    assert feed_out.read_text(encoding="utf-8") == before_feed
    capsys.readouterr()

    output.write_text(
        output.read_text(encoding="utf-8") + "\nstray edit\n", encoding="utf-8"
    )
    assert main(["--config", str(cfg), "--check"]) == 1

    output.unlink()
    assert main(["--config", str(cfg), "--check"]) == 1


