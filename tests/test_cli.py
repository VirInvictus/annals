def test_missing_config_is_an_error(tmp_path: Path, monkeypatch) -> None:
    empty = tmp_path / "empty"
    empty.mkdir()
    monkeypatch.chdir(empty)
    monkeypatch.setattr(annals.config, "repo_root", lambda: empty)
    monkeypatch.setenv("XDG_CONFIG_HOME", str(tmp_path / "xdg"))
