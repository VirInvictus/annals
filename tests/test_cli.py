def _git(path: Path, *args: str, env: dict | None = None) -> None:
    subprocess.run(
        ("git", "-C", str(path), *args),
        check=True,
        capture_output=True,
        text=True,
        env=env,
    )


def _init_repo(path: Path) -> None:
    path.mkdir(parents=True, exist_ok=True)
    _git(path, "init", "-b", "main")
    _git(path, "config", "user.email", "test@example.com")
    _git(path, "config", "user.name", "Test")


def _commit(
    path: Path,
    message: str,
    when: str,
    name: str = "Test",
    email: str = "test@example.com",
) -> None:
    env = os.environ | {
        "GIT_AUTHOR_DATE": when,
        "GIT_COMMITTER_DATE": when,
        "GIT_AUTHOR_NAME": name,
        "GIT_AUTHOR_EMAIL": email,
        "GIT_COMMITTER_NAME": name,
        "GIT_COMMITTER_EMAIL": email,
    }
    (path / "f.txt").write_text(message + "\n")
    _git(path, "add", "-A")
    subprocess.run(
        ("git", "-C", str(path), "commit", "-m", message),
        check=True,
        capture_output=True,
        text=True,
        env=env,
    )


def make_workspace(tmp_path: Path) -> Path:
    ws = tmp_path / "ws"
    release = ws / "repo-a"
    _init_repo(release)
    (release / "patchnotes.md").write_text(
        "## v1.1.0 (2026-03-05)\n\n### Two\n\n## v1.0.0 (2026-01-01)\n\n### One\n",
        encoding="utf-8",
    )
    _commit(release, "work", "2026-01-01T00:00:00")
    _commit(
        release,
        "upstream history",
        "2026-03-01T00:00:00",
        name="Upstream",
        email="jan@example.com",
    )

    stats_repo = ws / "sb"
    _init_repo(stats_repo)
    _commit(stats_repo, "work", "2026-02-01T00:00:00")

    excluded = ws / "calibre"
    _init_repo(excluded)
    (excluded / "patchnotes.md").write_text(
        "## v9.9.9 (2026-01-01)\n", encoding="utf-8"
    )
    _commit(excluded, "work", "2026-01-01T00:00:00")

    stray = ws / "stray"
    _init_repo(stray)
    _commit(stray, "work", "2026-01-01T00:00:00")
    return ws


def make_config(ws: Path, output: Path) -> Path:
    cfg = ws.parent / "annals.toml"
    site_out = ws.parent / "site" / "patchnotes.md"
    ledger_out = ws.parent / "site" / "_includes" / "ledger.md"
    feed_out = ws.parent / "site" / "patchnotes" / "feed.xml"
    cfg.write_text(
        "[workspace]\n"
        f'root = "{ws}"\n'
        'exclude = ["calibre"]\n'
        'stats_only = ["sb"]\n'
        "\n[run]\n"
        f'output = "{output}"\n'
        'intro = """Custom intro. Generated by {generator}. Ends here."""\n'
        "\n[stats]\n"
        'authors = ["test@example.com"]\n'
        'authors_display = "Test Author"\n'
        "\n[descriptions]\n"
        '"repo-a" = "The first repo"\n'
        "\n[links]\n"
        '"repo-a" = "https://example.com/repo-a"\n'
        "\n[site]\n"
        f'path = "{site_out}"\n'
        'front_matter = "---\\nlayout: default\\npermalink: /patchnotes/\\n---"\n'
        "\n[ledger]\n"
        f'path = "{ledger_out}"\n'
        "link_url = \"{{ '/p/' | relative_url }}\"\n"
        "\n[feed]\n"
        f'path = "{feed_out}"\n'
        'site_url = "https://example.com"\n'
        "limit = 1\n"
        'page_url = "https://example.com/p/"\n'
        'id = "tag:example.com,2026:/p/"\n'
        'subtitle = "Every release, newest first."\n',
        encoding="utf-8",
    )
    return cfg


def test_config_load_and_output_resolution(tmp_path: Path) -> None:
    ws = make_workspace(tmp_path)
    output = tmp_path / "out" / "RECORD.md"
    cfg = make_config(ws, output)
    config = load_config(cfg)
    assert config.workspace == ws
    assert config.output == output
    assert config.exclude == {"calibre"}
    assert config.stats_only == {"sb"}
    assert config.authors == ("test@example.com",)
    assert config.authors_display == "Test Author"
    assert config.descriptions == {"repo-a": "The first repo"}
    assert config.links == {"repo-a": "https://example.com/repo-a"}
    assert config.language_exclude == frozenset()
    assert config.intro == "Custom intro. Generated by {generator}. Ends here."
    assert config.site is not None
    assert config.site.path == tmp_path / "site" / "patchnotes.md"
    assert config.site.front_matter.startswith("---\n")
    assert config.ledger is not None
    assert config.ledger.path == tmp_path / "site" / "_includes" / "ledger.md"
    assert config.ledger.link_url == "{{ '/p/' | relative_url }}"
    assert config.feed is not None
    assert config.feed.path == tmp_path / "site" / "patchnotes" / "feed.xml"
    assert config.feed.site_url == "https://example.com"
    assert config.feed.limit == 1
    assert config.feed.page_url == "https://example.com/p/"
    assert config.feed.id == "tag:example.com,2026:/p/"
    assert config.feed.subtitle == "Every release, newest first."


