"""Renderer tests over synthetic records."""

from __future__ import annotations

from annals.gitstats import RepoStats
from annals.parse import Entry
from annals.render import Record, RepoRecord, render


def entry(
    repo: str,
    version: str | None,
    resolved: str | None,
    *,
    headline: str = "",
    approx: bool = False,
    source: str = "inline",
    kind: str = "release",
    index: int = 0,
) -> Entry:
    return Entry(
        repo=repo,
        kind=kind,
        version=version,
        headline=headline,
        resolved=resolved,
        approx=approx,
        source=source,
        index=index,
    )


def stats(first: str, last: str, monthly: dict[str, int], commits: int) -> RepoStats:
    return RepoStats(commits=commits, first=first, last=last, monthly=monthly)


def test_dashboard_timeline_and_coverage() -> None:
    busy = RepoRecord(
        name="busy",
        entries=[
            entry("busy", "2.0.0", "2026-10-09", headline="The big one", index=0),
            entry("busy", "1.9.0", "2026-09-14", headline="Steady", index=1),
        ],
        stats=stats("2026-05-01", "2026-10-09", {"2026-09": 40, "2026-10": 12}, 1_234),
    )
    approx_repo = RepoRecord(
        name="approx-repo",
        entries=[
            entry(
                "approx-repo",
                "0.2.0",
                "2026-01-01",
                headline="Guessed",
                approx=True,
                source="neighbor",
                index=0,
            ),
        ],
        stats=stats("2026-01-01", "2026-01-02", {"2026-01": 3}, 3),
    )
    undated = RepoRecord(
        name="undated-repo",
        entries=[
            entry(
                "undated-repo",
                "0.1.0",
                "2025-12-01",
                headline="Early days",
                source="first-commit",
                approx=True,
            )
        ],
        stats=stats("2025-12-01", "2025-12-01", {"2025-12": 1}, 1),
    )
    stats_only = RepoRecord(
        name="stats-only",
        entries=[],
        stats=stats("2026-02-01", "2026-02-02", {"2026-02": 2}, 2),
    )
    record = Record(
        repos=[busy, approx_repo, undated, stats_only],
        ignored=["stray-dir"],
        generated="2026-10-09",
        generator="annals 0.1.0",
    )
    text = render(record)

    # Masthead
    assert "# The Annals" in text
    assert "Generated by annals 0.1.0 on 2026-10-09." in text
    assert "remain canonical" in text

    # Dashboard: totals, per-repo table sorted by releases desc, latest column
    assert "4 repositories tracked · 4 releases recorded · 1,240 commits" in text
    assert "| busy | 2 | 2.0.0 | 2026-10-09 | 1,234 | 2026-05-01 |" in text
    assert "| approx-repo | 1 | 0.2.0 | ≈2026-01-01 | 3 | 2026-01-01 |" in text
    assert "| stats-only | 0 | - | - | 2 | 2026-02-01 |" in text
    assert busy_line_position(text) < approx_line_position(text)
    assert "This month (2026-10): 1 releases across 1 repos · 12 commits" in text

    # Monthly activity table has bars and a zero marker
    assert "| 2026-10 |" in text
    assert "▇" in text
    assert "| 2026-01 |" in text

    # Timeline: year/month grouping, descending; approx entries stay out
    assert "### 2026" in text
    assert "#### October 2026" in text
    assert "#### September 2026" in text
    assert "- **10-09 · busy 2.0.0** · The big one" in text
    assert "- **09-14 · busy 1.9.0** · Steady" in text
    assert "- **01-01 · approx-repo 0.2.0**" not in text
    assert text.index("#### October 2026") < text.index("#### September 2026")

    # Neighbor/first-commit entries land in the Undated records section
    assert "### Undated records" in text
    assert "#### undated-repo" in text
    assert "#### approx-repo" in text
    assert "- 0.2.0 · Guessed" in text

    # Coverage: source counts and ignored directories
    assert "| busy | 2 | 2 | 0 | 0 | 0 | 0 |" in text
    assert "| approx-repo | 1 | 0 | 0 | 1 | 0 | 0 |" in text
    assert "`stray-dir`" in text


def busy_line_position(text: str) -> int:
    return text.index("| busy |")


def approx_line_position(text: str) -> int:
    return text.index("| approx-repo |")


def test_empty_record_renders() -> None:
    record = Record(repos=[], generated="2026-10-09", generator="annals 0.1.0")
    text = render(record)
    assert "# The Annals" in text
    assert "0 repositories tracked · 0 releases recorded · 0 commits" in text
    assert "_Nothing dated to record yet._" in text
